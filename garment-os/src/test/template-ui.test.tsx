import { afterEach, beforeEach, expect, it } from 'vitest';
import { cleanup, fireEvent, render, screen } from '@testing-library/react';
import { TemplateManager } from '@/features/template-library/components/TemplateManager';
import { StandardGeneratorPanel } from '@/features/piece-library/StandardGeneratorPanel';
import { useDesignStore } from '@/store/useDesignStore';
import { usePieceLibraryStore } from '@/store/pieceLibraryStore';
import { generatePatternSheet } from '@/lib/svg-export/pattern-sheet-exporter';
import { PATTERN_LIBRARY } from '@/data/patternLibrary';
import { measurePieceBboxFull } from '@/lib/pattern/piece-registry';
beforeEach(() => { useDesignStore.getState().newDesign(); usePieceLibraryStore.getState().clearTagFilter(); });
afterEach(cleanup);
it('blocked cards cannot switch templates; categories control actual cards', () => {
  render(<TemplateManager />);
  expect(screen.getByTestId('template-v-neck-tee')).toBeDisabled();
  expect(screen.getByTestId('template-t-shirt-pro')).toBeDisabled();
  fireEvent.click(screen.getByText('Polo', { selector: 'button' }));
  expect(screen.queryByTestId('template-t-shirt')).toBeNull();
  expect(screen.getByTestId('template-polo-shirt')).toBeDisabled();
  fireEvent.click(screen.getByTestId('template-polo-shirt'));
  expect(useDesignStore.getState().activePatternId).toBe('brian-reference');
  fireEvent.click(screen.getByText('衬衫', { selector: 'button' }));
  fireEvent.click(screen.getByTestId('template-button-up-shirt'));
  expect(useDesignStore.getState().activePatternId).toBe('button-up-shirt');
});
it('the shirt generator filters to both collars, edits real geometry, blocks blanks and handles empty results', () => {
  useDesignStore.getState().applyPattern('button-up-shirt');
  const { container } = render(<StandardGeneratorPanel />);
  expect(container.querySelectorAll('[data-standard-piece]')).toHaveLength(10);
  fireEvent.click(screen.getByText('领类', { selector: 'button' }));
  expect([...container.querySelectorAll('[data-standard-piece]')].map(e => e.getAttribute('data-standard-piece'))).toEqual(['simon.collar','simon.collarStand']);
  const before = container.querySelector('[data-layer=net]')?.getAttribute('d') ?? container.querySelector('[data-source-path="simon.collar:seam"]')!.getAttribute('d');
  expect(container.querySelector('[data-source-path="simon.collar:underCollar"]')).toHaveAttribute('stroke-dasharray', '3 3');
  fireEvent.change(screen.getByLabelText('颈围'), { target: { value: '395' } });
  expect(container.querySelector('[data-source-path="simon.collar:seam"]')!.getAttribute('d')).not.toBe(before);
  fireEvent.change(screen.getByLabelText('颈围'), { target: { value: '' } });
  expect(screen.getByRole('alert')).toHaveTextContent('生成已阻断');
  expect(screen.getByTestId('standard-apply')).toBeDisabled();
  expect(screen.queryByTestId('standard-preview')).toBeNull();
  fireEvent.change(screen.getByLabelText('颈围'), { target: { value: '395' } });
  fireEvent.click(screen.getByText('清除筛选'));
  fireEvent.click(screen.getByText('口袋类', { selector: 'button' }));
  expect(screen.getByTestId('standard-empty')).toBeInTheDocument();
  expect(screen.queryByTestId('standard-preview')).toBeNull();
});
it('whole-sheet export contains every piece at real mm dimensions and refuses unverified tiled paper', () => {
  const s = useDesignStore.getState(); s.applyPattern('button-up-shirt');
  const paths = useDesignStore.getState().draft.paths;
  const svg = generatePatternSheet(PATTERN_LIBRARY['button-up-shirt'], paths);
  const doc = new DOMParser().parseFromString(svg, 'image/svg+xml');
  expect(doc.querySelector('parsererror')).toBeNull();
  expect(doc.querySelectorAll('path[data-piece]')).toHaveLength(paths.length);
  const undercollar = paths.find(p => p.id === 'simon.collar:underCollar')!;
  expect(doc.querySelector(`path[d="${undercollar.data}"]`)?.getAttribute('stroke-dasharray')).toBe('3 3');
  expect(doc.querySelector('[marker-start="url(#reference-grainlineFrom)"]')).not.toBeNull();
  const b = measurePieceBboxFull(paths);
  expect(parseFloat(doc.documentElement.getAttribute('width')!)).toBeGreaterThan(b.maxX-b.minX);
  expect(svg).toContain('productionApproved'); expect(svg).toContain('生产未验收');
  expect(() => generatePatternSheet(PATTERN_LIBRARY['button-up-shirt'],paths,{paperSize:'A4'})).toThrow(/分幅/);
});
